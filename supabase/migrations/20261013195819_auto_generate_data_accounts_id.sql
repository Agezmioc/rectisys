BEGIN;

-- Agregar IDENTITY solamente si la columna todavía no lo tiene.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'data_accounts'
          AND column_name = 'id'
          AND is_identity = 'YES'
    ) THEN
        ALTER TABLE public.data_accounts
            ALTER COLUMN id
            ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END
$$;

-- Sincronizar la secuencia con los IDs existentes.
SELECT setval(
    pg_get_serial_sequence('public.data_accounts', 'id'),
    COALESCE(MAX(id), 0) + 1,
    false
)
FROM public.data_accounts;

COMMIT;
